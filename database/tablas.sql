CREATE TABLE USUARIOS (
    RUT                 VARCHAR2(20) PRIMARY KEY,
    NOMBRE              VARCHAR2(100) NOT NULL,
    APELLIDO_PATERNO    VARCHAR2(100) NOT NULL,
    APELLIDO_MATERNO    VARCHAR2(100) NOT NULL,
    EMAIL               VARCHAR2(100) NOT NULL,
    CONTRASENIA         VARCHAR2(255) NOT NULL,
    TELEFONO            VARCHAR2(20),
    FECHA_REGISTRO      DATE DEFAULT SYSDATE NOT NULL,
    ROL                 VARCHAR2(20) NOT NULL,
    ESTADO_USUARIO      VARCHAR(20) DEFAULT 'activo' NOT NULL
);

CREATE TABLE CANCHAS (
    ID_CANCHA       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NOMBRE          VARCHAR2(100) NOT NULL,
    TIPO            VARCHAR2(50) NOT NULL,
    VALOR_HORA      NUMBER(10) NOT NULL,
    DESCRIPCION     VARCHAR2(500),
    ESTADO_CANCHA   VARCHAR2(20) DEFAULT 'activa' NOT NULL
);

CREATE TABLE RESERVAS (
    ID_RESERVA          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    ID_CANCHA           NUMBER NOT NULL,
    RUT_USUARIO         VARCHAR2(20) NOT NULL,
    FECHA_RESERVA       DATE NOT NULL,
    HORA_INICIO         VARCHAR2(5) NOT NULL, -- Formato 'HH:MM' (ej. '08:00')
    HORA_FIN            VARCHAR2(5) NOT NULL, -- Formato 'HH:MM' (ej. '09:00')
    VALOR_TOTAL         NUMBER NOT NULL,
    ESTADO_RESERVA      VARCHAR2(20) DEFAULT 'activa' NOT NULL,
    FECHA_CREACION      DATE DEFAULT SYSDATE NOT NULL,
    FECHA_CANCELACION   DATE,
    MOTIVO_CANCELACION  VARCHAR2(500)
);

CREATE TABLE DISPONIBILIDAD (
    ID_DISP         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    FECHA           DATE NOT NULL,
    ID_CANCHA       NUMBER NOT NULL,
    ID_RESERVA      NUMBER,
    INICIO_BLOQUE   VARCHAR2(5) NOT NULL, -- Formato 'HH:MM' (ej. '08:00')
    FIN_BLOQUE      VARCHAR2(5) NOT NULL, -- Formato 'HH:MM' (ej. '09:00')
    ESTADO          VARCHAR2(20) DEFAULT 'disponible' NOT NULL
);

CREATE TABLE PENALIZACIONES (
    ID_PENALIZACION       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    RUT_USUARIO           VARCHAR2(20) NOT NULL,
    ID_RESERVA            NUMBER NOT NULL,
    FECHA_PENALIZACION    DATE DEFAULT SYSDATE NOT NULL,
    TIPO_PENALIZACION     VARCHAR2(50) NOT NULL,
    MOTIVO                VARCHAR2(500) NOT NULL,
    ESTADO_PENALIZACION   VARCHAR2(20) DEFAULT 'activa' NOT NULL,
    COMENTARIOS_ADMIN     VARCHAR2(1000)
);

CREATE TABLE AUD_CANCHAS (
    ID_AUD_CANCHA       NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ID_CANCHA           NUMBER,
    NOMBRE_ANTERIOR     VARCHAR2(100),
    NOMBRE_NUEVO        VARCHAR2(100),
    VALOR_ANTERIOR      NUMBER,
    VALOR_NUEVO         NUMBER,
    OPERACION           VARCHAR2(10), -- 'UPDATE' o 'DELETE'
    FECHA_OPERACION     DATE,
    RUT_ADMIN           VARCHAR2(20)
);